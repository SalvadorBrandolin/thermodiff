__all__ = ["scalar_chain_workload_module", "scalar_chain_workload_procedures"]

#: Keywords forwarded to every ``to_fortran`` call of the core kernels.
_TO_FORTRAN_KEYS = ("integer_args", "module_symbols", "symmetric_params")
_INDENT = "   "
#: Default of the ``name`` argument (prefix of the total derivatives).
_DEFAULT_NAME = "ar"


@dataclasses.dataclass(frozen=True)
class _Context:
    """Everything the kernel generation of one call shares."""

    core: "DiffPlz"
    chain_args: Mapping[str, Any]
    core_name: str
    fixed: CodegenOptions
    passed: Mapping[str, Any]


def _declared_names(iface: KernelInterface) -> list[str]:
    """Return every name the kernel declares (dummies and locals)."""
    names: list[str] = []
    for line in iface.lines[iface.header_end :]:
        names += [dummy.name for dummy in _parse_declaration(line)]
    return names


def _check_clashes(
    iface: KernelInterface, pieces: ChainFragments, shared: Iterable[str]
) -> None:
    """Raise if the core kernel and the chain routine share a name.

    ``shared`` are the core derivatives, declared by both on purpose.
    """
    skip = {name.lower() for name in shared}
    core = {n.lower() for n in _declared_names(iface)} - skip
    chain = {n.lower() for n in pieces.dummies}
    for line in pieces.local_lines:
        chain |= {n.strip().lower() for n in line.split("::")[-1].split(",")}
    clash = sorted((core & chain) - skip)
    if clash:
        raise ValueError(
            f"{iface.name}: names {clash} are used by the core kernel and "
            "by the chain routine; rename a scalar"
        )


def _make_value_optional(text: str, value: str) -> str:
    """Guard the assignment of the function value with ``present()``."""
    pattern = re.compile(rf"^(\s*){re.escape(value)} = ", re.M)
    guarded, count = pattern.subn(rf"\1if (present({value})) {value} = ", text)
    if count != 1:
        raise ValueError(f"cannot find the assignment of {value!r}")
    return guarded


def _kind_lines(lines: Iterable[str], options: CodegenOptions) -> list[str]:
    """Express chain declarations in the real kind of the kernel."""
    return [apply_real_kind(line, options.real_kind, None) for line in lines]


@dataclasses.dataclass(frozen=True)
class _Editor:
    """Declaration editor of the core kernel inside a fused kernel.

    The core derivatives the chain reads become locals; the value is made
    optional when ``optional_value`` is set.
    """

    hidden: frozenset[str]
    value: str
    optional_value: bool

    def __call__(self, dummy: Dummy) -> Dummy:
        """Return the declaration of ``dummy`` in the fused kernel."""
        if dummy.name.lower() in self.hidden:
            return dataclasses.replace(dummy, attrs=[])
        if self.optional_value and dummy.name == self.value:
            attrs = ["optional", *dummy.attrs]
            return dataclasses.replace(dummy, attrs=attrs)
        return dummy


def _value_output(iface: KernelInterface, hidden: frozenset[str]) -> str:
    """Return the name of the function value output of the core kernel."""
    values = [arg for arg in iface.outputs if arg.lower() not in hidden]
    if len(values) != 1:
        raise ValueError("the core kernel must have one value output")
    return values[0]


def _dummy_name(declaration: str) -> str:
    """Return the name declared by a dummy declaration line."""
    return declaration.split("::")[1].split("(")[0].strip()


def fuse_kernel(
    core_text: str,
    pieces: ChainFragments,
    *,
    name: str,
    options: CodegenOptions,
    optional_value: bool = False,
) -> str:
    """Merge a core kernel and a chain routine into one subroutine.

    Parameters
    ----------
    core_text : str
        Kernel of the core with every core derivative the chain reads as
        an ``intent(out)`` dummy.
    pieces : ChainFragments
        The chain routine; its core derivative inputs become locals.
    name : str
        Name of the fused subroutine.
    options : CodegenOptions
        Real kind of the chain declarations.
    optional_value : bool, optional
        Make the function value an optional output.

    Returns
    -------
    str
        The subroutine.  Arguments: ``nc``, the inputs of the core, the
        value, the other inputs of the chain, the outputs of the chain.

    Raises
    ------
    ValueError
        If the core has an ``nc`` argument, names clash or the core has not
        exactly one value output.
    """
    iface = parse_kernel(core_text)
    if iface.has_nc:
        raise ValueError("a scalar core has no 'nc' argument")
    _check_clashes(iface, pieces, pieces.inputs.core)
    hidden = frozenset(item.lower() for item in pieces.inputs.core)
    value = _value_output(iface, hidden)
    core_args = [a for a in iface.args if a.lower() not in hidden]
    chain_args = [d for d in pieces.dummies if d.lower() not in hidden]
    declarations = [
        line
        for line in pieces.declarations
        if _dummy_name(line).lower() not in hidden
    ]
    text = render_kernel(
        iface,
        name=name,
        args=[NC_NAME, *core_args, *chain_args[1:]],
        edit=_Editor(hidden, value, optional_value),
        after_implicit=_kind_lines(
            [*declarations, *pieces.local_lines], options
        ),
    )
    end = f"end subroutine {name}"
    head = text.rpartition(end)[0]
    chain = "\n".join(
        _INDENT + line for line in _kind_lines(pieces.body, options)
    )
    text = f"{head}{chain}\n{end}"
    return _make_value_optional(text, value) if optional_value else text


def _core_derivative_names(
    pieces: ChainFragments, core_name: str
) -> list[str]:
    """Return the core derivatives the chain reads, for ``to_fortran``."""
    prefix = f"d{core_name}"
    table = pieces.inputs.core
    ordered = sorted(table, key=lambda item: table[item])
    return [item[len(prefix) :] for item in ordered]


def _fused(
    context: _Context,
    selection: Any,
    name: str,
    *,
    optional: bool,
) -> str:
    """Generate the fused kernel of one output selection.

    With ``optional`` the chain outputs and the value are optional (the
    fallback); the core derivatives are then those of ``selection``, all
    computed.
    """
    model, requested = resolve_chain(
        **context.chain_args, derivatives=selection
    )
    pieces = chain_fragments(model, requested, optional)
    names = _core_derivative_names(pieces, context.core_name)
    core_text = to_fortran(
        context.core,
        derivatives=names,
        subroutine_name=f"{name}_core",
        options=context.fixed,
        **context.passed,
    )
    return fuse_kernel(
        core_text,
        pieces,
        name=name,
        options=context.fixed,
        optional_value=optional,
    )


def _fixed_kernel(
    context: _Context,
    selection: Any,
    name: str,
    fallback: KernelInterface,
    taken: Iterable[int],
) -> tuple[_Specialised, str]:
    """Generate one fixed-output fused kernel and its dispatcher data."""
    iface = parse_kernel(_fused(context, selection, name, optional=False))
    mask = _check_against_fallback(iface, fallback, output_bits(fallback))
    if mask in taken:
        raise ValueError(f"workload {selection!r} repeats an output set")
    kernel = _Specialised(
        name, iface, mask, {}, shape_guard(iface, {}), NC_DUMMY_NAME
    )
    return kernel, specialise_kernel(iface, name=name, extents={})


def scalar_chain_workload_procedures(
    core: "DiffPlz",
    scalars: Sequence[str],
    workloads: Sequence[Any],
    depends_on: Mapping[str, Iterable[str]] | None = None,
    *,
    linear: Iterable[str] = (),
    total_moles: Iterable[str] = (),
    zero: Iterable[str] | None = None,
    thermo: Sequence[str] = THERMO_VARIABLES,
    derivatives: object = "all",
    core_name: str = "f",
    name: str = _DEFAULT_NAME,
    subroutine_name: str | None = None,
    preset: Preset | str | None = None,
    options: CodegenOptions | None = None,
    **kwargs: Any,
) -> str:
    """Generate the dispatcher, the fallback and the fused kernels.

    Parameters
    ----------
    core : DiffPlz
        The scalar core (``DiffPlz(..., variables=[...])``).
    scalars, depends_on, linear, total_moles, zero, thermo, core_name, name
        As in :func:`~thermodiff.codegen.core_chain.scalar_chain_routine`.
    workloads : sequence
        One selection of chain outputs per fused kernel, in the format of
        ``scalar_chain_routine(derivatives=...)`` (for example
        ``["dv", "dni"]``).  The function value ``f`` is an output of every
        kernel.  The dispatcher matches the output set exactly.
    derivatives : str or list of str, optional
        Outputs of the dispatcher and so of its signature; it must contain
        every workload (default: all the outputs).
    subroutine_name : str, optional
        Public name of the dispatcher (default ``<name>_fused``); the
        kernels are ``<name>_fallback`` and ``<name>_w<k>``.
    preset, options, **kwargs
        Code-generation options of the core kernels as in ``to_fortran``
        (``real_kind``, ``kind_module`` and the other option names are
        accepted as overrides; ``module_symbols``, ``integer_args`` and
        ``symmetric_params`` are forwarded to every ``to_fortran`` call).
        ``optional_derivatives`` is decided here.

    Returns
    -------
    str
        The subroutines, without a module.  The dispatcher has the
        arguments ``nc``, the inputs of the core, ``f``, the inputs of the
        chain (optional: an output needs its inputs present) and the
        optional outputs.

    Raises
    ------
    ValueError
        If two workloads have the same outputs, a workload is not covered by
        ``derivatives`` or names clash.
    """
    passed = {k: kwargs.pop(k) for k in _TO_FORTRAN_KEYS if k in kwargs}
    fixed, _ = _resolve_pair(preset, options, kwargs)
    chain_args = dict(
        scalars=scalars,
        depends_on=depends_on,
        linear=linear,
        total_moles=total_moles,
        core=core,
        zero=zero,
        thermo=thermo,
        core_name=core_name,
        name=name,
    )
    context = _Context(core, chain_args, core_name, fixed, passed)
    base = subroutine_name or f"{name}_fused"
    fallback_name = f"{base}_fallback"
    fallback_text = _fused(context, derivatives, fallback_name, optional=True)
    fallback = parse_kernel(fallback_text)
    kernels: list[_Specialised] = []
    texts: list[str] = []
    for position, selection in enumerate(workloads, start=1):
        kernel, text = _fixed_kernel(
            context,
            selection,
            f"{base}_w{position}",
            fallback,
            [k.mask for k in kernels],
        )
        kernels.append(kernel)
        texts.append(text)
    reserved = list(passed.get("module_symbols") or ())
    dispatcher = build_dispatcher(
        base, fallback, fallback_name, kernels, [], reserved
    )
    return "\n\n".join([dispatcher, fallback_text, *texts]) + "\n"


def scalar_chain_workload_module(
    core: "DiffPlz",
    scalars: Sequence[str],
    workloads: Sequence[Any],
    depends_on: Mapping[str, Iterable[str]] | None = None,
    *,
    module_name: str | None = None,
    uses: Iterable[str] = (),
    **kwargs: Any,
) -> str:
    """Generate a Fortran module of fused scalar-chain workload kernels.

    Parameters
    ----------
    core, scalars, workloads, depends_on
        See :func:`scalar_chain_workload_procedures`.
    module_name : str, optional
        Name of the module (default ``<dispatcher name>_mod``).
    uses : iterable of str, optional
        Text after ``use`` for each module-level statement.
    **kwargs
        See :func:`scalar_chain_workload_procedures`.

    Returns
    -------
    str
        The complete module.
    """
    code = scalar_chain_workload_procedures(
        core, scalars, workloads, depends_on, **kwargs
    )
    base = kwargs.get("subroutine_name") or (
        f"{kwargs.get('name', _DEFAULT_NAME)}_fused"
    )
    return wrap_module(
        module_name or f"{base}_mod",
        uses,
        code,
        [
            "! Generated by thermodiff (fused scalar-chain workloads).",
            "! Do not edit by hand.",
        ],
    )
