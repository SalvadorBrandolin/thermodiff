"""Fused workload kernels of a scalar core.

A scalar core is evaluated in two steps: the core kernel
(``to_fortran(core, derivatives=...)``) gives the derivatives of
``F(x_1, ..., x_m; V, T)`` and the chain routine
(:func:`~thermodiff.codegen.core_chain.scalar_chain_routine`) assembles the
total derivatives from them.  Called as two procedures every evaluation pays
two calls, the copies of the intermediate derivatives and the optional
argument tests of the chain routine.

:func:`scalar_chain_workload_module` emits instead, for each *workload* (a
set of chain outputs such as ``["dv", "dni"]``), one subroutine that

* computes exactly the core derivatives the workload needs, as local
  scalars, with the code the generator produces for that fixed set;
* assembles exactly the outputs of the workload from them, with no optional
  argument and no ``present()`` test;

and a dispatcher with the full signature (optional outputs) that selects the
subroutine by the ``present()`` mask of the outputs, as the workload mode
does (:mod:`thermodiff.codegen.workload`, whose dispatcher it reuses).

The kernels are composed, not printed again: the core kernel is generated by
``to_fortran``, parsed, and its derivative outputs become locals; the
declarations and statements of the chain routine
(:func:`~thermodiff.codegen.core_chain.chain_fragments`) are inserted after
``implicit none`` and before ``end subroutine``.

Fallback
--------
The kernel for any output set that is not a workload computes *every*
core derivative that the union of the outputs needs and then runs the chain
routine with optional outputs.  That is the simplest correct choice: a core
derivative is a function of the scalars alone, so computing one nobody asked
for needs no extra input, and the fused all-optional kernel would otherwise
need a ``present()`` test per core derivative.  The value ``F`` is an
optional output of the dispatcher too (bit of the mask), and so are the
inputs that only some outputs need (scalar derivatives).  The chain routine
with optional outputs computes the total partials ``q_W,r`` when *any*
second-order ``T``/``V`` output is present, so a call that is not a workload
must pass the inputs of every such output it needs for all of ``T`` and
``V`` on which a scalar depends (the workloads have no such restriction).
"""

